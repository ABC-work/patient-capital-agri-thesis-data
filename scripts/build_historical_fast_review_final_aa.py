def ratio(n,d): return format(n/d,"f")
def threshold(lo,hi): return "是" if lo >= D(".5") else ("否" if hi < D(".5") else "待核实")
def boundary(lo,hi):
    if lo >= D(".5") or hi < D(".3"): return "否"
    if lo >= D(".3") and hi < D(".5"): return "是"
    return "待核实"


