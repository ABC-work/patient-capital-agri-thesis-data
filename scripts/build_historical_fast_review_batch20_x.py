def ratio(n, d):
    return format(n / d, "f")


def threshold(lo, hi):
    return "是" if lo >= D("0.5") else ("否" if hi < D("0.5") else "待核实")


def boundary(lo, hi):
    if lo >= D("0.5") or hi < D("0.3"):
        return "否"
    if lo >= D("0.3") and hi < D("0.5"):
        return "是"
    return "待核实"


def profit_pages(code, year, original):
    return "100" if (code, year) == ("002505", 2016) else original


