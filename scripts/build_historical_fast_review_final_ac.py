D = Decimal


def q(x):
    return D(str(x))


def ratio(n, d):
    return format(q(n) / q(d), "f")


def threshold(lo, hi, total):
    lo, hi, total = q(lo) / q(total), q(hi) / q(total), q(total)
    return "是" if lo >= D(".5") else ("否" if hi < D(".5") else "待核实")


def boundary(lo, hi, total):
    lo, hi = q(lo) / q(total), q(hi) / q(total)
    if lo >= D(".5") or hi < D(".3"):
        return "否"
    if lo >= D(".3") and hi < D(".5"):
        return "是"
    return "待核实"


