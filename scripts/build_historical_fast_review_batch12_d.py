def raw(n, d): return format(n / d, "f")
def r8(n, d): return (n/d).quantize(Decimal("0.00000001"), rounding=ROUND_HALF_UP)

def threshold(lower, upper):
    if lower >= Decimal("0.50"): return "是"
    if upper < Decimal("0.50"): return "否"
    return "待核实"

def boundary(lower, upper):
    if lower >= Decimal("0.50") or upper < Decimal("0.30"): return "否"
    if lower >= Decimal("0.30") and upper < Decimal("0.50"): return "是"
    return "待核实"

